# Generates wcwidth-table.h, the column widths wcwidth() reports in a UTF-8
# locale, from three files of the Unicode Character Database:
#
#   https://www.unicode.org/Public/<version>/ucd/UnicodeData.txt
#   https://www.unicode.org/Public/<version>/ucd/EastAsianWidth.txt
#   https://www.unicode.org/Public/<version>/ucd/DerivedCoreProperties.txt
#
# usage: wcwidth-gen.py <directory with the three files> > wcwidth-table.h
#
# Rules, in order of precedence:
#   -1  not printable: Cc, Cs, Cn (unassigned and noncharacters), Zl, Zp
#    0  U+0000; Mn, Me; Default_Ignorable_Code_Point except U+00AD SOFT HYPHEN
#       and U+115F HANGUL CHOSEONG FILLER; the Hangul Jamo medial vowels and
#       final consonants (U+1160-U+11FF, U+D7B0-U+D7FF), which combine with the
#       preceding initial consonant into one syllable cell
#    2  East_Asian_Width W or F (this covers the emoji with default emoji
#       presentation), and U+3248-U+324F (circled numbers on black squares)
#    1  everything else, including the private use planes
# These reproduce glibc's wcwidth() exactly for every code point when both use
# the same Unicode version (checked against glibc 2.43 with Unicode 17.0.0).
#
# Copyright 2026 Phoenix Systems
#
# This file is part of Phoenix-RTOS.
#
# %LICENSE%
#

import os
import re
import sys

CODE_POINTS = 0x110000


def fields(path):
    """Yields the ';'-separated fields of each data line of a UCD file."""
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if line != '':
                yield [x.strip() for x in line.split(';')]


def code_range(spec):
    first, _, last = spec.partition('..')
    return int(first, 16), int(last if last != '' else first, 16)


def main():
    ucd = sys.argv[1]

    version = '?'
    with open(os.path.join(ucd, 'EastAsianWidth.txt'), encoding='utf-8') as f:
        m = re.search(r'EastAsianWidth-([0-9.]+)\.txt', f.readline())
        if m is not None:
            version = m.group(1)

    # General_Category; ranges are given as <..., First> / <..., Last> pairs
    category = ['Cn'] * CODE_POINTS
    first = None
    for f in fields(os.path.join(ucd, 'UnicodeData.txt')):
        cp = int(f[0], 16)
        if f[1].endswith(', First>'):
            first = cp
            continue
        start = first if f[1].endswith(', Last>') else cp
        for c in range(start, cp + 1):
            category[c] = f[2]
        first = None

    wide = [False] * CODE_POINTS
    for f in fields(os.path.join(ucd, 'EastAsianWidth.txt')):
        if f[1] in ('W', 'F'):
            lo, hi = code_range(f[0])
            for c in range(lo, hi + 1):
                wide[c] = True

    ignorable = [False] * CODE_POINTS
    for f in fields(os.path.join(ucd, 'DerivedCoreProperties.txt')):
        if f[1] == 'Default_Ignorable_Code_Point':
            lo, hi = code_range(f[0])
            for c in range(lo, hi + 1):
                ignorable[c] = True

    def width(c):
        if c == 0:
            return 0
        if category[c] in ('Cc', 'Cs', 'Cn', 'Zl', 'Zp'):
            return -1
        if category[c] in ('Mn', 'Me'):
            return 0
        if ignorable[c] and c not in (0x00ad, 0x115f):
            return 0
        if (0x1160 <= c <= 0x11ff) or (0xd7b0 <= c <= 0xd7ff):
            return 0
        if wide[c] or (0x3248 <= c <= 0x324f):
            return 2
        return 1

    # The table is the code space cut into runs of equal width: the first code
    # point of each run, with that width.
    runs = []
    prev = None
    for c in range(CODE_POINTS):
        w = width(c)
        if w != prev:
            runs.append((c, w))
            prev = w

    out = sys.stdout
    out.write('/*\n'
              ' * Phoenix-RTOS\n'
              ' *\n'
              ' * libphoenix\n'
              ' *\n'
              ' * Column widths for wcwidth() in a UTF-8 locale, Unicode %s.\n'
              ' *\n'
              ' * GENERATED by wcwidth-gen.py from the Unicode Character Database files\n'
              ' * UnicodeData.txt, EastAsianWidth.txt and DerivedCoreProperties.txt;\n'
              ' * do not edit. The rules are described in wcwidth-gen.py.\n'
              ' *\n'
              ' * Each entry starts a run of code points of one width, which lasts until\n'
              ' * the next entry: WCWIDTH_RUN(first code point, width).\n'
              ' *\n'
              ' * Copyright 2026 Phoenix Systems\n'
              ' *\n'
              ' * This file is part of Phoenix-RTOS.\n'
              ' *\n'
              ' * %%LICENSE%%\n'
              ' */\n\n' % version)
    out.write('#define WCWIDTH_UNICODE_VERSION "%s"\n\n' % version)
    out.write('static const uint32_t wcwidth_runs[%d] = {\n' % len(runs))
    per_line = 4
    for i in range(0, len(runs), per_line):
        chunk = runs[i:i + per_line]
        out.write('\t' + ' '.join('WCWIDTH_RUN(0x%06x, %2d),' % r for r in chunk) + '\n')
    out.write('};\n')


if __name__ == '__main__':
    main()
